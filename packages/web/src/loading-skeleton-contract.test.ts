import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import test from 'node:test'

const source = (path: string) => readFileSync(new URL(path, import.meta.url), 'utf8')

test('loading skeletons reflect the current Task Center rows and flat session reader', () => {
  const shared = source('./components/StateViews.tsx')
  const review = source('./components/ReviewStateOverlay.tsx')
  const taskCenter = source('./features/TaskCenterPage.tsx')
  const styles = source('./states.css')
  const railStyles = source('./task-center.css')
  assert.match(shared, /className="session-skeleton-row"/)
  assert.match(shared, /className="review-detail-skeleton-header"/)
  assert.match(shared, /className="review-detail-skeleton-user"/)
  assert.match(shared, /className="review-detail-skeleton-answer"/)
  assert.doesNotMatch(shared, /review-detail-skeleton-metrics|session-skeleton-card/)
  assert.match(taskCenter, /review\.loading && !review\.response && <SessionListSkeleton\/>/)
  assert.match(taskCenter, /<Suspense fallback=\{<ReviewDetailSkeleton\/>\}>/)
  assert.doesNotMatch(taskCenter, /task-center-list-skeleton/)
  assert.doesNotMatch(review, /<SessionListSkeleton\/>/)
  assert.match(review, /<ReviewDetailSkeleton\/>/)
  assert.doesNotMatch(styles, /review-state-session|review-detail-skeleton-metrics/)
  assert.doesNotMatch(railStyles, /task-center-list-skeleton/)
})

test('workspace loading states share one owner with semantic geometry for each view', () => {
  const shared = source('./components/StateViews.tsx')
  const agents = source('./features/AgentsPage.tsx')
  const agentsOverlay = source('./components/AgentsStateOverlay.tsx')
  const insights = source('./features/InsightsPage.tsx')
  const tools = source('./features/ToolsPage.tsx')
  const styles = source('./states.css')
  assert.match(shared, /'agents' \| 'insights' \| 'tools'/)
  assert.match(shared, /kind === 'agents'/)
  assert.match(shared, /kind === 'insights'/)
  assert.match(shared, /kind === 'tools'/)
  assert.match(agents, /<WorkspaceSkeleton kind="agents"\/>/)
  assert.match(agentsOverlay, /<WorkspaceSkeleton kind="agents"\/>/)
  assert.match(insights, /insights\.loading && !data \? <WorkspaceSkeleton kind="insights"\/>/)
  assert.match(tools, /usage\.loading && !data \? <WorkspaceSkeleton kind="tools"\/>/)
  assert.match(styles, /\.workspace-skeleton-coverage\{/)
  assert.match(styles, /\.workspace-skeleton-agent-info\{/)
  assert.match(styles, /\.workspace-skeleton-table-row\{/)
  assert.doesNotMatch(styles, /workspace-skeleton-cards|workspace-skeleton-kpis/)
})

test('page loading uses actual status, not fictional progress, and backup failures remain actionable', () => {
  const shared = source('./components/StateViews.tsx')
  const backup = source('./features/BackupPage.tsx')
  const styles = source('./states.css')
  assert.match(shared, /className="page-loading-state" role="status"/)
  assert.doesNotMatch(shared, /page-loading-preview|page-loading-progress/)
  assert.doesNotMatch(styles, /\.page-loading-preview|\.page-loading-progress/)
  assert.match(styles, /prefers-reduced-motion:reduce/)
  assert.match(backup, /&& error && !loading/)
  assert.match(backup, /<ErrorStateBanner message=\{error\} onRetry=/)
  assert.match(backup, /if \(!overview \|\| overview\.index\?\.ready === false\)/)
})
