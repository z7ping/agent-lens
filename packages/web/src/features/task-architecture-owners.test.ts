import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import test from 'node:test'

const view = (path: string) => readFileSync(new URL(path, import.meta.url), 'utf8')
const client = (path: string) => readFileSync(new URL(`../client/${path}`, import.meta.url), 'utf8')

test('Live 组件、异步生命周期、双向分页、动作、状态与输入各有唯一所有者', () => {
  const page = view('./LiveTaskPage.tsx')
  const runtime = view('./use-live-task-runtime.ts')
  const history = view('./use-live-task-history.ts')
  const actions = view('./use-live-task-actions.ts')
  const state = view('./live-task-state.ts')
  const timeline = view('./LiveTaskTimeline.tsx')
  const window = view('./live-task-history-window.ts')
  const queue = view('./live-task-queue.ts')
  const input = view('./live-task-input.ts')

  assert.match(page, /useLiveTaskState\(\)/)
  assert.match(page, /useLiveTaskRuntime\(\{ current, t, session \}\)/)
  assert.match(page, /useLiveTaskHistory\(\{ current, session \}\)/)
  assert.match(page, /useLiveTaskActions\(\{ current, t, navigate, setComposerValue, clearComposer, session, onSendAccepted, onSendDelivered \}\)/)
  assert.match(page, /<TaskSurface\s+mode="live"/)
  assert.doesNotMatch(page, /const \[product, setProduct\] = useState/)
  assert.doesNotMatch(page, /const unsubscribe = liveApi\.subscribe\(/)

  assert.match(state, /export function useLiveTaskState/)
  assert.match(state, /new LiveTaskRoundProjector\(\)/)
  assert.match(runtime, /const unsubscribe = liveApi\.subscribe\(/)
  assert.match(runtime, /const recoverOnce = async/)
  assert.match(runtime, /reconcileState\(shouldRecoverLiveOnVisible/)
  assert.match(history, /IntersectionObserver/)
  assert.match(history, /compactHistoryBlocks/)
  assert.match(actions, /liveApi\.send\(/)
  assert.match(actions, /liveApi\.interrupt\(/)
  assert.match(actions, /liveApi\.respondToExtension\(/)
  assert.match(timeline, /export const StableLiveRounds = memo/)
  assert.match(window, /export const LIVE_TASK_HISTORY_WINDOW_MAX_PAGES = 5/)
  assert.match(history, /import \{[^\n]*LIVE_TASK_HISTORY_WINDOW_MAX_PAGES/)
  assert.match(queue, /export function restoredQueueDrafts/)
  assert.match(input, /export async function optimisticMessageAttachments/)
})

test('Review 将证据检查器、轮次演示、会话编排和 Reader 定位分离', () => {
  const page = view('./ReviewPage.tsx')
  const session = view('./use-review-session.ts')
  const evidence = view('./ReviewEvidenceInspector.tsx')
  const rounds = view('./ReviewRoundPresentation.tsx')
  const reader = view('./review-reader-position.ts')
  assert.match(page, /useReviewSession\(model, embedded\)/)
  assert.match(page, /<ReviewRoundAdapter/)
  assert.match(page, /<Inspector/)
  assert.match(session, /model\.loadMoreReviewDetail\(/)
  assert.match(rounds, /export function ReviewRoundAdapter/)
  assert.match(evidence, /export function Inspector/)
  assert.match(reader, /export function captureReviewReaderPosition/)
  assert.match(reader, /export function restoreReviewReaderPosition/)
  assert.doesNotMatch(page, /function ReviewProcessGroup/)
  assert.doesNotMatch(page, /function RawInspectorContent/)
})

test('客户端模型按领域单向继承，原有 model.ts 只做公共入口', () => {
  const api = client('model.ts')
  const base = client('model-base.ts')
  const integrations = client('model-integration.ts')
  const review = client('model-review.ts')
  const usage = client('model-usage.ts')
  assert.match(api, /export \{ AgentLensClientModel \} from '\.\/model-usage'/)
  assert.match(api, /export type \{ ClientSnapshot \} from '\.\/model-base'/)
  assert.match(base, /export abstract class AgentLensModelBase/)
  assert.match(integrations, /extends AgentLensModelBase/)
  assert.match(review, /extends AgentLensIntegrationModel/)
  assert.match(usage, /extends AgentLensReviewModel/)
  assert.match(usage, /async refreshUsage\(\)/)
  assert.doesNotMatch(base, /from '\.\/model-integration'/)
  assert.doesNotMatch(integrations, /from '\.\/model-review'/)
  assert.doesNotMatch(review, /from '\.\/model-usage'/)
})
